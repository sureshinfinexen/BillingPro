def t(key: str, lang: str = "en") -> str:
    row = _STRINGS.get(key) or {}
    return row.get(lang) or row.get("en") or key


def d(text, lang: str = "en") -> str:
    """Localize known stored/seed display values. Unknown text (and SKUs) stay as-is."""
    if text is None:
        return ""
    s = str(text).strip()
    if not s:
        return s
    row = _DISPLAY.get(s)
    if row:
        return row.get(lang) or row.get("en") or s
    return s


def und(text, lang: str = "en") -> str:
    """Normalize a localized known value back to English for storage."""
    if text is None:
        return ""
    s = str(text).strip()
    if not s:
        return s
    if s in _DISPLAY:
        return s
    for en, row in _DISPLAY.items():
        if s == row.get("ta") or s == row.get("hi") or s == row.get("en"):
            return en
    return s


def translator(lang: str):
    def _tr(key: str) -> str:
        return t(key, lang)
    return _tr


def display_fn(lang: str):
    def _d(text) -> str:
        return d(text, lang)
    return _d
